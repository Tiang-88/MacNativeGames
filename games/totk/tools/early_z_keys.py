#!/usr/bin/env python3
"""Write totk_early_z_keys.h: the fragment shaders whose NVN control section asks for early fragment tests.

Control byte +0x718 of a fragment shader's NVN control section is its early fragment tests flag (upstream PR #222):
the Switch tests depth before the shader when it is set. The rule here is the translator's: the 0x880-byte sections only,
skipping the shorter ones Breath of the Wild uses (the size word at +0x20 between 0x7cc and 0x880).

Reads a prepared seed's inventory (inventory.json + shaders.bin), which holds every shader's control section and code.
    python3 tools/early_z_keys.py --inventory build/shader-seed/v121-new.inventory
"""
import argparse
import json
import struct


def early_z_keys(inventory_dir):
    inv = json.load(open(f"{inventory_dir}/inventory.json"))
    seeds = inv["identity"]
    ps = {}
    with open(f"{inventory_dir}/shaders.bin", "rb") as blobs:
        for key, row in inv["shaders"].items():
            stage, _container, ofs, clen, _code_ofs, _code_len = row
            if stage != "ps" or key in ps:
                continue
            blobs.seek(ofs)
            control = blobs.read(clen)
            if len(control) < 0x720:
                continue
            size = struct.unpack_from("<I", control, 0x20)[0]
            ps[key] = bool(not (0x7CC <= size < 0x880) and control[0x718] & 1)
    return seeds, ps


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--inventory", default="build/shader-seed/v121-new.inventory")
    ap.add_argument("--out", default="third_party/d2r_gfx/gfx/nvn/totk_early_z_keys.h")
    a = ap.parse_args()
    seeds, ps = early_z_keys(a.inventory)
    keys = sorted(k for k, early in ps.items() if early)
    for k in keys:
        assert len(k) == 64 and all(c in "0123456789abcdef" for c in k), k
    with open(a.out, "w") as f:
        f.write("// TOTK_EARLY_Z: the fragment shaders whose NVN control section asks for early fragment tests (control byte\n"
                "// +0x718 & 1 of the 0x880-byte section; the shorter sections Breath of the Wild uses are not read).\n"
                f"// Generated by tools/early_z_keys.py from {a.inventory} (preparation_sha256\n"
                f"// {seeds['preparation_sha256']}): {len(keys)} of {len(ps)} fragment shaders. Sorted; look up with\n"
                "// totk_early_z_lookup (binary search).\n"
                "#pragma once\n"
                "static const char *const k_early_z_keys[] = {\n")
        for i in range(0, len(keys), 3):
            f.write("".join(f'    "{k}",\n' for k in keys[i:i + 3]))
        f.write("};\n")
    print(f"{a.out}: {len(keys)} of {len(ps)} fragment shaders ask for early fragment tests")


if __name__ == "__main__":
    main()
